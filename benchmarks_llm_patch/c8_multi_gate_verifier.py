"""
Component C8: Closed-Loop Multi-Gate Verification Oracle
Evaluates candidate security patches generated by C7 across 4 formal verification gates:
  - Gate 1: Tree-sitter CST Re-parse (Zero Syntax Errors, Error Recovery Check)
  - Gate 2: Interface Preservation (Function Signature Integrity)
  - Gate 3: Taint Path Broken (Security Flaw Elimination Check)
  - Gate 4: Maintainability Delta (Cyclomatic Complexity CC & SLOC)
"""

import ast
import re
from pathlib import Path
from typing import Dict, Any, Tuple, Optional
import tree_sitter_python as tspython
from tree_sitter import Language, Parser

PY_LANGUAGE = Language(tspython.language())
ts_parser = Parser(PY_LANGUAGE)


def extract_code_from_markdown(raw_output: str) -> str:
    """Extract python code from ```python ... ``` blocks, stripping backticks and language headers."""
    pattern = r"```(?:python|py)?\s*\n(.*?)\n```"
    match = re.search(pattern, raw_output, flags=re.DOTALL)
    if match:
        return match.group(1).strip()
    # Fallback: strip leading/trailing ```
    cleaned = re.sub(r"^```(?:python|py)?\s*\n?", "", raw_output.strip())
    cleaned = re.sub(r"\n?```\s*$", "", cleaned)
    return cleaned.strip("` \t\r\n")


def calculate_cyclomatic_complexity(code_str: str) -> int:
    """
    Computes McCabe Cyclomatic Complexity using AST decision points:
    CC = 1 + Decisions (If, For, While, And, Or, ExceptHandler, With, etc.)
    """
    try:
        tree = ast.parse(code_str)
    except SyntaxError:
        return 999

    complexity = 1
    for node in ast.walk(tree):
        if isinstance(node, (ast.If, ast.While, ast.For, ast.AsyncFor)):
            complexity += 1
        elif isinstance(node, ast.BoolOp):
            complexity += len(node.values) - 1
        elif isinstance(node, ast.ExceptHandler):
            complexity += 1
        elif isinstance(node, (ast.Assert, ast.IfExp)):
            complexity += 1
    return complexity


class MultiGateVerifier:
    @staticmethod
    def verify_gate1_syntax(patch_code: str) -> Tuple[bool, str]:
        """
        Gate 1: Tree-sitter CST re-parse.
        Ensures zero ERROR nodes exist in the concrete syntax tree.
        """
        code_bytes = patch_code.encode("utf-8")
        tree = ts_parser.parse(code_bytes)

        if tree.root_node.has_error:
            def find_error(node):
                if node.type == "ERROR" or node.is_missing:
                    return f"ERROR node at byte [{node.start_byte}:{node.end_byte}]"
                for child in node.children:
                    res = find_error(child)
                    if res:
                        return res
                return None

            err_msg = find_error(tree.root_node) or "Tree-sitter detected syntax defect"
            return False, f"Gate 1 Failed (Tree-sitter CST): {err_msg}"

        try:
            ast.parse(patch_code)
        except SyntaxError as e:
            return False, f"Gate 1 Failed (Python AST SyntaxError): {e.msg} at line {e.lineno}"

        return True, "Gate 1 Passed: 100% syntactically valid CST"

    @staticmethod
    def verify_gate2_interface(original_code: str, patch_code: str, expected_func_name: str) -> Tuple[bool, str]:
        """
        Gate 2: Interface Preservation.
        Ensures function name and parameter names are preserved.
        """
        try:
            orig_ast = ast.parse(original_code)
            patch_ast = ast.parse(patch_code)
        except Exception:
            return False, "Gate 2 Failed: Unable to parse AST for signature extraction"

        orig_fn = None
        for node in ast.walk(orig_ast):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == expected_func_name:
                orig_fn = node
                break

        patch_fn = None
        for node in ast.walk(patch_ast):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == expected_func_name:
                patch_fn = node
                break

        if not patch_fn:
            return False, f"Gate 2 Failed: Expected function '{expected_func_name}' not found in patch"

        orig_args = [a.arg for a in orig_fn.args.args]
        patch_args = [a.arg for a in patch_fn.args.args]

        if orig_args != patch_args:
            return False, f"Gate 2 Failed: Parameter signature mismatch. Original {orig_args} vs Patch {patch_args}"

        return True, f"Gate 2 Passed: Function signature '{expected_func_name}{tuple(orig_args)}' strictly preserved"

    @staticmethod
    def verify_gate3_taint_neutralization(cwe_id: str, patch_code: str) -> Tuple[bool, str]:
        """
        Gate 3: Taint Path Broken (Security Flaw Elimination).
        Heuristically and structurally checks whether the vulnerable sink was eliminated.
        """
        if cwe_id == "CWE-78":
            if "shell=True" in patch_code:
                return False, "Gate 3 Failed: Vulnerable 'shell=True' remains in subprocess call"
            if "subprocess" in patch_code and ("shlex" in patch_code or "[" in patch_code or "ipaddress" in patch_code):
                return True, "Gate 3 Passed: shell=True eliminated, parameterized argument list used"
            return True, "Gate 3 Passed: OS command sink safely re-routed"

        if cwe_id == "CWE-89":
            if re.search(r"execute\s*\(\s*f[\"']", patch_code):
                return False, "Gate 3 Failed: SQL query still constructed with dynamic f-string"
            if re.search(r"execute\s*\(\s*.*%\s*\(", patch_code):
                return False, "Gate 3 Failed: SQL query still constructed with raw % formatting"
            if re.search(r"execute\s*\(\s*query\s*,\s*\(", patch_code) or "execute(query," in patch_code or "%s" in patch_code or "?" in patch_code or ", (" in patch_code:
                return True, "Gate 3 Passed: Query successfully parameterized with placeholder tuple"
            return True, "Gate 3 Passed: Dynamic SQL injection neutralized"

        if cwe_id == "CWE-79":
            if "escape(" in patch_code or "html.escape" in patch_code or "sanitize" in patch_code:
                return True, "Gate 3 Passed: Untrusted input neutralized via HTML escaping"
            return False, "Gate 3 Failed: Output contains raw unescaped input without html.escape"

        if cwe_id == "CWE-22":
            if "realpath" in patch_code or "resolve" in patch_code or "startswith" in patch_code or "abspath" in patch_code:
                return True, "Gate 3 Passed: Path resolution and canonical directory boundary check enforced"
            return False, "Gate 3 Failed: Relative path not validated against directory traversal"

        if cwe_id == "CWE-502":
            if "pickle.loads" in patch_code:
                return False, "Gate 3 Failed: Dangerous 'pickle.loads' remains in code"
            if "json" in patch_code or "hmac" in patch_code or "safe" in patch_code:
                return True, "Gate 3 Passed: Insecure pickle replaced with safe serialization format"
            return True, "Gate 3 Passed: Insecure deserialization sink eliminated"

        return True, f"Gate 3 Passed: Flaw {cwe_id} pattern remediated"

    @staticmethod
    def verify_gate4_maintainability(orig_code: str, patch_code: str) -> Tuple[bool, Dict[str, Any]]:
        """
        Gate 4: Maintainability Delta.
        Calculates CC before vs after, and line delta.
        Delta CC = CC_after - CC_before (should be <= 0 or small for defensive check).
        """
        cc_before = calculate_cyclomatic_complexity(orig_code)
        cc_after = calculate_cyclomatic_complexity(patch_code)

        sloc_before = len([l for l in orig_code.splitlines() if l.strip() and not l.strip().startswith("#")])
        sloc_after = len([l for l in patch_code.splitlines() if l.strip() and not l.strip().startswith("#")])

        delta_cc = cc_after - cc_before
        passed = delta_cc <= 2  # Allows slight increase for defense-in-depth guardrails

        metrics = {
            "cc_before": cc_before,
            "cc_after": cc_after,
            "delta_cc": delta_cc,
            "sloc_before": sloc_before,
            "sloc_after": sloc_after,
            "delta_sloc": sloc_after - sloc_before,
            "passed": passed
        }
        return passed, metrics


def verify_patch(orig_code: str, patch_raw: str, cwe_id: str, func_name: str) -> Dict[str, Any]:
    """Runs all 4 C8 verification gates on a generated raw patch."""
    clean_code = extract_code_from_markdown(patch_raw)

    g1_ok, g1_msg = MultiGateVerifier.verify_gate1_syntax(clean_code)
    if not g1_ok:
        return {
            "all_passed": False,
            "failed_gate": "Gate 1 (Syntax)",
            "g1_syntax": (g1_ok, g1_msg),
            "g2_interface": (False, "Skipped due to syntax failure"),
            "g3_taint": (False, "Skipped due to syntax failure"),
            "g4_maintainability": (False, {}),
            "clean_code": clean_code
        }

    g2_ok, g2_msg = MultiGateVerifier.verify_gate2_interface(orig_code, clean_code, func_name)
    g3_ok, g3_msg = MultiGateVerifier.verify_gate3_taint_neutralization(cwe_id, clean_code)
    g4_ok, g4_metrics = MultiGateVerifier.verify_gate4_maintainability(orig_code, clean_code)

    all_passed = bool(g1_ok and g2_ok and g3_ok and g4_ok)
    failed_gate = None
    if not all_passed:
        if not g2_ok:
            failed_gate = "Gate 2"
        elif not g3_ok:
            failed_gate = "Gate 3"
        else:
            failed_gate = "Gate 4"

    return {
        "all_passed": all_passed,
        "failed_gate": failed_gate,
        "g1_syntax": (g1_ok, g1_msg),
        "g2_interface": (g2_ok, g2_msg),
        "g3_taint": (g3_ok, g3_msg),
        "g4_maintainability": (g4_ok, g4_metrics),
        "clean_code": clean_code
    }
