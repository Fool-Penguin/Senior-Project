"""Step 2: measure every selected repository at its pinned commit.

Usage: python -I scripts/measure.py [--dataset=NAME] [key ...]  (no keys = every repo in data/webapp/selected_repos.csv)
For each repo: fetch exactly the pinned commit (depth 1, no checkout: files are read from git objects,
so Windows path limits and line-ending settings cannot change the content), drop excluded files,
measure, resolve imports, write data/webapp/repo_metrics/<key>/{files.csv,functions.csv,summary.json}, delete the fetch.
Repos that already have summary.json are skipped (resume). Output is sorted, so reruns are byte-identical.
"""
import csv
import json
import os
import re
import subprocess
import sys
import tempfile
import threading
import time
from collections import Counter, defaultdict
from concurrent.futures import ProcessPoolExecutor, as_completed
from importlib.metadata import version
from pathlib import Path, PurePosixPath

sys.path.insert(0, str(Path(__file__).resolve().parent))
from metrics import LANGUAGE, measure  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
# --dataset=NAME reads/writes data/NAME/; default = the web-app benchmark
DATASET = next((a.split("=", 1)[1] for a in sys.argv[1:] if a.startswith("--dataset=")), "webapp")
SELECTED = ROOT / "data" / DATASET / "selected_repos.csv"
OUT = ROOT / "data" / DATASET / "repo_metrics"
MAX_BYTES = 1_000_000

# Exclusions (Alves et al. 2010 removed test and generated code; examples/docs added by user decision)
DIRS = {
    "test": {"test", "tests", "__tests__", "testing", "spec", "specs", "__mocks__", "__snapshots__", "e2e",
             "fixtures", "__fixtures__", "qa"},
    "generated_vendored": {"node_modules", "bower_components", "vendor", "vendors", "third_party", "thirdparty",
                           "3rdparty", "dist", "build", ".next", "coverage", "site-packages", "venv", ".venv",
                           "migrations", "generated", "__generated__", "__generated", "__pycache__", "libs",
                           "external", "externals", "third-party", "3rd-party"},
    "example_docs": {"example", "examples", "doc", "docs", "demo", "demos", "sample", "samples", "cookbook",
                     "cookbooks", "tutorial", "tutorials", "playground"},
}
FILES = {
    "test": re.compile(r"(^|/)(test_[^/]*\.py|[^/]*_test\.py|conftest\.py|tests?\.py)$"
                       r"|\.(test|spec|e2e|cy)\.[cm]?[jt]sx?$", re.I),
    "generated_vendored": re.compile(r"\.min\.[cm]?js$|\.bundle\.js$|\.d\.[cm]?ts$|_pb2(_grpc)?\.py$"
                                     r"|\.(generated|gen)\.[cm]?[jt]sx?$", re.I),
    "example_docs": re.compile(r"\.stories\.[cm]?[jt]sx?$", re.I),
}
GENERATED_HEADER = re.compile(rb"@generated|auto-?generated|do not (edit|modify)|this file (is|was|has been) "
                              rb"(automatically )?generated|code generated by", re.I)
CONFIG = re.compile(r"(^|/)((ts|js)config[^/]*\.json|package\.json"
                    r"|(vite|vitest|webpack|vue|next|nuxt|babel)\.config[^/]*\.[cm]?[jt]s|\.babelrc(\.json)?)$")
# Python project roots: packaging files, Django manage.py, requirements*.txt (wsgi.py/asgi.py: see python_roots)
ROOT_MARKER = re.compile(r"(^|/)(pyproject\.toml|setup\.py|setup\.cfg|manage\.py|requirements[^/]*\.txt)$")


def path_reason(path):
    parts = path.lower().split("/")
    for part in parts[:-1]:
        if part.startswith("."):
            return "hidden_dir"  # .github, .vscode, .storybook ... (tooling, not product code)
        for reason, names in DIRS.items():
            if part in names:
                return reason
    for reason, pattern in FILES.items():
        if pattern.search(path):
            return reason
    return None


# Third-party JS/TS copied into the repo (PDF.js, CodeMirror, jQuery, lodash ...): a release banner with a version
# ("/*! jQuery v3.7.1"), a UMD wrapper (define.amd), a @license/@licstart tag, or Emscripten glue code.
# A plain "/*! Copyright <company>" banner is NOT enough: some projects put it on their own files (e.g. Planka).
VENDORED_HEADER = re.compile(rb"/\*!(?:(?!\*/).){0,400}?\bv?\d+\.\d+\.\d+|define\.amd|@license\b|@licstart"
                             rb"|Module = typeof Module", re.S)
DATA_FILE_SLOC = 1000  # JS/TS file this large without any function = data (dictionaries, lists)


def content_reason(data, path=""):
    if GENERATED_HEADER.search(data[:2048]):
        return "generated_vendored"
    if not path.endswith(".py") and VENDORED_HEADER.search(data[:4096]):
        return "vendored_library"
    lines = data.count(b"\n") + 1
    if len(data) / lines > 200 and max(len(line) for line in data.split(b"\n")) > 1000:
        return "generated_vendored"  # minified / bundled
    return None


def git(gitdir, *args, **kw):
    # GIT_NO_LAZY_FETCH: never download filtered-out blobs behind our back (fail loudly instead)
    env = {**os.environ, "GIT_TERMINAL_PROMPT": "0", "GIT_NO_LAZY_FETCH": "1"}
    # no background gc/maintenance: a detached git process would keep the temp folder locked on Windows
    return subprocess.run(["git", "-c", "gc.auto=0", "-c", "maintenance.auto=false", "-C", gitdir, *args],
                          capture_output=True, check=True, env=env, **kw).stdout


TOO_BIG = 1 << 30  # size given to blobs left out by the partial fetch (>= 1 MiB, so always > MAX_BYTES)


def ls_tree(gitdir, sha):
    """[(path, blob_sha, size)] of regular files at the commit (symlinks and submodules skipped).
    Sizes come from the downloaded objects only (`ls-tree -l` would download the filtered-out blobs)."""
    sizes = {}
    for line in git(gitdir, "cat-file", "--batch-all-objects", "--batch-check=%(objectname) %(objectsize)").split(b"\n"):
        if line:
            obj, size = line.split()
            sizes[obj.decode()] = int(size)
    out = []
    for entry in git(gitdir, "ls-tree", "-r", "-z", "--full-tree", sha).split(b"\0"):
        if not entry:
            continue
        meta, path = entry.split(b"\t", 1)
        mode, kind, obj = meta.split()
        if kind == b"blob" and mode in (b"100644", b"100755"):
            out.append((path.decode("utf-8", "replace"), obj.decode(), sizes.get(obj.decode(), TOO_BIG)))
    return sorted(out)


def read_blobs(gitdir, shas):
    proc = subprocess.Popen(["git", "-C", gitdir, "cat-file", "--batch"], env={**os.environ, "GIT_NO_LAZY_FETCH": "1"},
                            stdin=subprocess.PIPE,
                            stdout=subprocess.PIPE)

    def feed():
        proc.stdin.write("".join(s + "\n" for s in shas).encode())
        proc.stdin.close()

    threading.Thread(target=feed, daemon=True).start()
    try:
        for _ in shas:
            size = int(proc.stdout.readline().split()[2])
            data = proc.stdout.read(size)
            proc.stdout.read(1)
            yield data
    finally:  # runs on exhaustion or blobs.close()
        proc.stdout.close()
        proc.wait()


def parent(path):
    return path.rsplit("/", 1)[0] if "/" in path else ""


def python_roots(all_paths, py_paths):
    """Project roots for absolute imports: the repo root, every dir holding a ROOT_MARKER file, and their src/.
    wsgi.py/asgi.py mark the dir above their package (Django: mysite/wsgi.py) or their own dir (Flask).
    Markers inside excluded dirs (docs/, tests/, examples/ ...) are ignored."""
    roots = {""}
    for p in all_paths:
        if path_reason(p):
            continue
        if ROOT_MARKER.search(p):
            roots.add(parent(p))
        elif PurePosixPath(p).name in ("wsgi.py", "asgi.py"):
            d = parent(p)
            roots.add(parent(d) if f"{d}/__init__.py".lstrip("/") in py_paths else d)
    return sorted(roots | {f"{r}/src".lstrip("/") for r in roots
                           if any(p.startswith(f"{r}/src/".lstrip("/")) for p in py_paths)})


def python_targets(path, imports, py_paths, roots, stats=None, names=frozenset()):
    """Repo .py files imported by `path`. Relative imports resolve from the file's package; absolute imports
    are tried against the project roots enclosing the file (deepest first), the other roots, the file's dir,
    then every other ancestor dir of the file (deepest first). The first base that matches wins.
    stats (Counter): `ambiguous` = absolute imports matched by more than one base; `unresolved` = relative
    imports with no match, and absolute imports whose top-level name is in `names` (repo dirs / .py stems)."""
    def module_file(base, dotted):
        rel = "/".join(x for x in [base, *dotted.split(".")] if x)
        cands = (f"{rel}.py", f"{rel}/__init__.py") if dotted else (f"{rel}/__init__.py".lstrip("/"),)
        return next((c for c in cands if c in py_paths), None)

    here = parent(path)
    ancestors = sorted((r for r in roots if r == "" or path.startswith(r + "/")), key=lambda r: (-r.count("/") - bool(r), r))
    others = [r for r in roots if r not in ancestors]
    above, d = [], here
    while d:
        d = parent(d)
        above.append(d)
    absolute_bases = list(dict.fromkeys(ancestors + others + [here] + above))
    targets = set()
    for level, module, imported in imports:
        if level:
            base = here
            for _ in range(level - 1):
                base = parent(base)
            bases = [base]
        else:
            bases = absolute_bases
        hits = []
        for base in bases:
            # `from m import a`: a may be a submodule m/a.py, otherwise it is a name defined in m itself
            found = {f for f in (module_file(base, f"{module}.{n}" if module else n) for n in imported) if f}
            if len(found) < len(imported) or not imported:
                package = module_file(base, module)
                if package:
                    found.add(package)
            if found:
                hits.append(found)
        if hits:
            targets |= hits[0]
        if stats is not None:
            if len(hits) > 1:
                stats["ambiguous"] += 1
            elif not hits and (level or module.split(".")[0] in names):
                stats["unresolved"] += 1
    targets.discard(path)
    return targets


def import_graph(all_paths, measured, config_text):
    """Internal import edges {file: set of measured files it imports} and import statistics.
    all_paths: every file of the repo snapshot; measured: {path: FileResult}; config_text: {path: text}."""
    py_paths = {p for p in all_paths if p.endswith(".py")}
    roots = python_roots(all_paths, py_paths)
    names = {seg for p in py_paths for seg in p[:-3].split("/")}
    edges, type_edges, py_stats = defaultdict(set), defaultdict(set), Counter()
    queries, js_type_specs = [], {}
    for path, result in sorted(measured.items()):
        if result.language == "python":
            edges[path] = python_targets(path, result.imports, py_paths, roots, py_stats, names)
            typed = [i for i, t in zip(result.imports, result.type_only) if t]
            if typed:  # edges that exist only through `if TYPE_CHECKING:` imports
                runtime = [i for i, t in zip(result.imports, result.type_only) if not t]
                type_edges[path] = (python_targets(path, typed, py_paths, roots)
                                    - python_targets(path, runtime, py_paths, roots))
        else:
            specs = sorted(set(result.imports))
            js_type_specs[path] = set(specs) - {s for s, t in zip(result.imports, result.type_only) if not t}
            queries += [[path, spec] for spec in specs]
    resolved, alias_unresolved = [], 0
    if queries:
        # package.json under excluded dirs (examples/, docs/ ...) must not claim a workspace package name
        config_text = {p: t for p, t in config_text.items() if not (p.endswith("package.json") and path_reason(p))}
        payload = json.dumps({"paths": all_paths, "configs": config_text, "queries": queries})
        out = json.loads(subprocess.run(["node", str(ROOT / "scripts" / "resolve_imports.mjs")],
                                        input=payload.encode(), capture_output=True, check=True, cwd=ROOT).stdout)
        resolved, alias_unresolved = out["resolved"], out["alias_unresolved"]
        value_targets = defaultdict(set)
        for (path, spec), target in zip(queries, resolved):
            if target:
                edges[path].add(target)
                (type_edges if spec in js_type_specs[path] else value_targets)[path].add(target)
        for path in js_type_specs:
            type_edges[path] -= value_targets[path]
    graph = {p: {t for t in edges[p] if t in measured and t != p} for p in measured}
    type_only = Counter(measured[p].language == "python" for p in measured for t in type_edges[p] if t in graph[p])
    return graph, {
        "js_relative_imports_unresolved": sum(1 for (_, s), t in zip(queries, resolved) if t is None and s.startswith(".")),
        "js_alias_imports_unresolved": alias_unresolved,
        "js_type_only_import_edges": type_only[False],
        "py_imports_ambiguous": py_stats["ambiguous"],
        "py_imports_unresolved": py_stats["unresolved"],
        "py_type_only_import_edges": type_only[True],
    }


def measure_repo(row):
    key, url, sha = row["key"], row["url"], row["sha"]
    with tempfile.TemporaryDirectory(prefix=f"thr_{key}_") as gitdir:
        git(gitdir, "init", "-q", "--bare")
        # partial fetch: blobs >= 1 MiB (images, videos, archives) are not downloaded. Files above MAX_BYTES
        # (< 1 MiB) are never read, so the measured content is identical, only the download is much smaller.
        git(gitdir, "remote", "add", "origin", url)
        git(gitdir, "config", "remote.origin.promisor", "true")
        for attempt in range(3):  # transient network errors: retry before giving up
            try:
                git(gitdir, "fetch", "-q", "--depth", "1", "--no-tags", "--filter=blob:limit=1m", "origin", sha,
                    timeout=3600)
                break
            except (subprocess.CalledProcessError, subprocess.TimeoutExpired):
                if attempt == 2:
                    raise
                time.sleep(30)
        tree = ls_tree(gitdir, sha)
        excluded = Counter()
        candidates = []
        for path, obj, size in tree:
            ext = PurePosixPath(path).suffix.lower()
            if ext not in LANGUAGE:
                continue
            reason = path_reason(path) or ("generated_vendored" if size > MAX_BYTES else None)
            if reason:
                excluded[reason] += 1
            else:
                candidates.append((path, obj))
        configs = [(p, o) for p, o, s in tree if CONFIG.search(p) and "node_modules/" not in p and s <= MAX_BYTES]
        blobs = read_blobs(gitdir, [o for _, o in candidates] + [o for _, o in configs])
        measured = {}
        for path, _ in candidates:
            data = next(blobs)
            reason = content_reason(data, path)
            if reason is None:
                try:
                    result = measure(path, data)
                except RecursionError:
                    result = None
                reason = "parse_error" if result is None else None
                if result and result.language != "python" and not result.units and result.sloc >= DATA_FILE_SLOC:
                    reason = "data_file"
            if reason:
                excluded[reason] += 1
            else:
                measured[path] = result
        config_text = {p: next(blobs).decode("utf-8", "replace") for p, _ in configs}
        blobs.close()

    graph, import_stats = import_graph([p for p, _, _ in tree], measured, config_text)
    ce = {p: len(graph[p]) for p in measured}
    ca = Counter(t for p in measured for t in graph[p])

    out = OUT / key
    out.mkdir(parents=True, exist_ok=True)
    with (out / "files.csv").open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["path", "language", "sloc", "cloc", "ce", "ca"])
        for path in sorted(measured):
            r = measured[path]
            w.writerow([path, r.language, r.sloc, r.cloc, ce[path], ca[path]])
    with (out / "functions.csv").open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["path", "language", "name", "kind", "start_line", "end_line", "sloc", "cyclomatic", "cognitive",
                    "params", "cognitive_sloc"])
        for path in sorted(measured):
            for u in measured[path].units:
                w.writerow([path, measured[path].language, u.name, u.kind, u.start_line, u.end_line, u.sloc,
                            u.cyclomatic, u.cognitive, u.params, u.cognitive_sloc])
    summary = {
        "key": key, "url": url, "branch": row["branch"], "sha": sha,
        "files_measured": dict(sorted(Counter(r.language for r in measured.values()).items())),
        "files_excluded": dict(sorted(excluded.items())),
        "functions": sum(len(r.units) for r in measured.values()),
        "internal_import_edges": sum(ce.values()),
        **import_stats,
        "tools": {"tree-sitter": version("tree-sitter"),
                  "tree-sitter-language-pack": version("tree-sitter-language-pack"),
                  "typescript": json.loads((ROOT / "node_modules" / "typescript" / "package.json").read_text())["version"]},
    }
    (out / "summary.json").write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return summary


def run_one(row):
    try:
        s = measure_repo(row)
        return f"{row['key']}: {s['files_measured']} functions={s['functions']} excluded={s['files_excluded']}"
    except (subprocess.CalledProcessError, subprocess.TimeoutExpired, OSError) as e:
        # nothing is written for a failed repo; rerunning the script retries it
        return f"{row['key']}: FAILED {e!r:.200} {getattr(e, 'stderr', b'')!r:.300}"


def main():
    """--jobs=N measures N repos in parallel; each repo's output is independent, so results are identical."""
    keys = [a for a in sys.argv[1:] if not a.startswith("--")]
    jobs = int(next((a.split("=", 1)[1] for a in sys.argv[1:] if a.startswith("--jobs=")), "1"))
    with SELECTED.open(encoding="utf-8", newline="") as f:
        rows = [r for r in csv.DictReader(f) if (not keys or r["key"] in keys)
                and not (OUT / r["key"] / "summary.json").exists()]
    with ProcessPoolExecutor(max_workers=jobs) as pool:
        for i, done in enumerate(as_completed([pool.submit(run_one, r) for r in rows]), 1):
            print(f"[{i}/{len(rows)}] {done.result()}", flush=True)


if __name__ == "__main__":
    main()
