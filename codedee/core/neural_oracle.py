def get_catalogue_metadata(cwe_id: str) -> dict:
    """Lookup deterministic Catalogue metadata for a given CWE ID."""
    cwe = (cwe_id or "").upper().strip()
    if not cwe or cwe in ("CWE-NONE", "NONE", "SAFE"):
        return CATALOGUE_METADATA["CWE-NONE"]
    return CATALOGUE_METADATA.get(
        cwe,
        {
            "catalogue_id": "UNMAPPED",
            "cwe_name": f"Security Weakness ({cwe})",
            "risk_level": "Medium",
            "cvss_v31_base": 5.0,
            "owasp_category": "Other",
            "remediation_guidance": "Neutralize untrusted input before reaching the sensitive execution sink.",
        },
    )


