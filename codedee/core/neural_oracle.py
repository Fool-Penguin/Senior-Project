    def _call_ollama(self, prompt: str) -> str:
        payload = {
            "model": self.model_name,
            "prompt": prompt,
            "system": SYSTEM_PROMPT,
            "stream": False,
            "format": "json",
            "options": {"temperature": 0.1, "top_p": 0.9, "num_predict": 1024},
        }
        data = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            f"{self.ollama_url}/api/generate",
            data=data,
            headers={"Content-Type": "application/json"},
        )
        try:
            with urllib.request.urlopen(req, timeout=120) as response:
                res_json = json.loads(response.read().decode("utf-8"))
                return res_json.get("response", "")
        except Exception:
            return ""

    def _parse_json(self, raw_text: str, fallback_cwe: str) -> dict:
        default_res = {
            "vulnerability_detected": True,
            "cwe_id": fallback_cwe,
            "reason": "Analyzed by symbolic walker (LLM response unavailable).",
        }
        if not raw_text:
            return default_res

        text = raw_text.strip()
        if text.startswith("```"):
            text = re.sub(r"^```[a-zA-Z]*\n?", "", text)
            text = re.sub(r"\n?```$", "", text)

        try:
            return json.loads(text)
        except Exception:
            json_block = re.search(r"\{[\s\S]*\}", text)
            if json_block:
                try:
                    return json.loads(json_block.group(0))
                except Exception:
                    pass
        return default_res
