from pathlib import Path

# Load GitHub Token
token = None
env_candidates = [
    Path(".env"),
    Path(__file__).resolve().parent / ".env",
    Path(__file__).resolve().parents[2] / ".env"
]
for p in env_candidates:
    if p.exists():
        with open(p, "r", encoding="utf-8") as f:
            for line in f:
                if line.startswith("GITHUB_TOKEN"):
                    token = line.split("=", 1)[1].strip().strip('"').strip("'")
        if token:
            break

headers = {
    "User-Agent": "DatasetBuilder-5000/1.0",
    "Accept": "application/vnd.github.v3+json"
}
if token:
    headers["Authorization"] = f"token {token}"

# --- Strict Disambiguated Signatures ---

INTERACTIVE_AI_GIT_TRAILERS = [
    (r"Co-authored-by:\s*(?:Claude|Cursor|Copilot|GitHub\s*Copilot|Windsurf|Codeium|Qodo)\s*<", "Git Trailer: Co-authored-by AI"),
    (r"Co-authored-by:.*<(?:noreply@anthropic\.com|cursoragent@cursor\.com|copilot@github\.com)>", "Git Trailer: AI Provider Email"),
    (r"Generated-by:\s*(?:Claude|Cursor|Copilot|Windsurf|Codeium)", "Git Trailer: Generated-by AI"),
    (r"\bAI-assisted\b(?:\s*\(Claude Code\)|\s*\(Cursor\)|\s*\(Copilot\))?", "Message Disclosure: AI-assisted"),
    (r"\bAI-generated\b", "Message Disclosure: AI-generated")
]

AUTONOMOUS_AI_GIT_SIGNATURES = [
    (r"^sweep(?:-ai)?(?:\[bot\])?$", "Actor Login: Sweep AI Autonomous Agent"),
    (r"^devin(?:-ai)?(?:-integration)?(?:\[bot\])?$", "Actor Login: Devin Autonomous Agent"),
    (r"^clawsweeper$", "Actor Login: ClawSweeper Autonomous Agent"),
    (r"steipete\+clawsweeper@gmail\.com", "Author Email: ClawSweeper"),
    (r"Co-authored-by:.*<(?:contact@sweep\.dev|devin.*@cognition\.ai)>", "Git Trailer: Autonomous Agent Email (Sweep/Devin)"),
    (r"Co-authored-by:\s*(?:Sweep|Devin|ClawSweeper)", "Git Trailer: Sweep/Devin Autonomous Agent"),
    (r"This PR was generated by\s+(?:Sweep|Devin)", "Message Disclosure: Autonomous Agent Generator")
]

DEVOPS_BOT_GIT_SIGNATURES = [
    (r"^dependabot(?:\[bot\])?$", "Actor Login: Dependabot"),
    (r"^renovate(?:\[bot\])?$", "Actor Login: Renovate"),
    (r"^github-actions(?:\[bot\])?$", "Actor Login: GitHub Actions"),
    (r"\[bot\]$", "Generic Bot Login [bot]"),
    (r"bot$", "Generic Bot Login suffix 'bot'")
]

# PR-Level Signatures (Exact, Disambiguated)
PR_INTERACTIVE_AI_LABELS = {"cursor", "claude-code", "ai-assisted", "ai-generated", "copilot"}
PR_AUTONOMOUS_AI_LABELS = {"sweep", "devin"}
PR_DEVOPS_BOT_LABELS = {"dependencies", "automated-pr", "bot"}

PR_BODY_CHECKBOX_PATTERNS = [
    (r"\[x\]\s*(?:AI[- ]assisted|Assisted\s+with\s+(?:Claude|Cursor|Copilot|AI))", "PR Checkbox: AI-assisted"),
    (r"\[x\]\s*(?:AI[- ]generated|Generated\s+with\s+(?:Claude|Cursor|Copilot|AI))", "PR Checkbox: AI-generated"),
    (r"\[x\]\s*Co-authored\s+with\s+Claude\s+Code", "PR Checkbox: Claude Code Co-author")
]

PR_BODY_ATTRIBUTION_PATTERNS = [
    (r"Generated\s+with\s+(?:Claude Code|Cursor|GitHub Copilot|Windsurf)", "PR Body: Tool Generation Watermark"),
    (r"Co-authored-by:\s*(?:Claude|Cursor|Copilot|claude-flow)\s*<", "PR Body: Co-authored-by AI Trailer"),
    (r"🤖\s*Generated with\s+\[?claude-flow\]?", "PR Body: claude-flow Generator"),
    (r"Claude-Session:\s*https?://claude\.ai/code/session", "PR Body: Claude Code Session Link"),
    (r"This PR was generated by\s+(?:\[Sweep\]|Sweep|Devin)", "PR Body: Autonomous Agent Generator"),
]

def fetch_json(url):
    req = urllib.request.Request(url, headers=headers)
    try:
        with urllib.request.urlopen(req) as resp:
            return json.loads(resp.read().decode("utf-8")), None
    except urllib.error.HTTPError as e:
        if e.code in (403, 429):
            time.sleep(5)
            return None, "RateLimit"
        return None, e.code
    except Exception as e:
        return None, str(e)

def get_target_repos(csv_path="Repos_Final_Sample.csv"):
    candidates = [
        Path(csv_path),
        Path(__file__).resolve().parents[2] / "02_repo_sampling" / "data" / csv_path,
        Path("02_repo_sampling/data") / csv_path,
        Path("../data") / csv_path,
    ]
    resolved_path = None
    for c in candidates:
        if c.exists():
            resolved_path = c
            break

    if not resolved_path:
        return []

    repos = []
    with open(resolved_path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            url = row.get("Repo_URL", "").strip()
            name = row.get("Repo_Name", "").strip() or row.get("\ufeffRepo_Name", "").strip()
            if url:
                parts = url.rstrip("/").split("/")
                if len(parts) >= 2:
                    repos.append((name, f"{parts[-2]}/{parts[-1]}", url))
    return repos

def classify_commit(commit_obj, pr_obj=None, owner_repo=""):
    c = commit_obj.get("commit", {})
    git_author = c.get("author", {}) or {}
    message = c.get("message", "") or ""
    gh_author = commit_obj.get("author") or {}
    gh_committer = commit_obj.get("committer") or {}

    author_login = gh_author.get("login", "")
    committer_login = gh_committer.get("login", "")
    author_name = git_author.get("name", "")
    author_email = git_author.get("email", "")

    interactive_clues = []
    autonomous_clues = []
    devops_clues = []

    # 1. Baseline Git Metadata
    for pat, desc in INTERACTIVE_AI_GIT_TRAILERS:
        if re.search(pat, message, re.IGNORECASE):
            interactive_clues.append(f"Commit Message: {desc}")
        if re.search(pat, author_name, re.IGNORECASE):
            interactive_clues.append(f"Author Name: {desc}")

    for pat, desc in AUTONOMOUS_AI_GIT_SIGNATURES:
        if author_login and re.search(pat, author_login, re.IGNORECASE):
            autonomous_clues.append(f"Actor Login: {desc}")
        if committer_login and re.search(pat, committer_login, re.IGNORECASE):
            autonomous_clues.append(f"Committer Login: {desc}")
        if author_email and re.search(pat, author_email, re.IGNORECASE):
            autonomous_clues.append(f"Author Email: {desc}")
        if re.search(pat, message, re.IGNORECASE):
            autonomous_clues.append(f"Commit Message: {desc}")

    for pat, desc in DEVOPS_BOT_GIT_SIGNATURES:
        if author_login and re.search(pat, author_login, re.IGNORECASE):
            devops_clues.append(f"Actor Login: {desc}")
        if committer_login and re.search(pat, committer_login, re.IGNORECASE):
            devops_clues.append(f"Committer Login: {desc}")
        if author_email and re.search(pat, author_email, re.IGNORECASE):
            devops_clues.append(f"Author Email: {desc}")

    # 2. PR-Level Signals
    pr_clues = []
    if pr_obj:
        pr_num = pr_obj.get("number")
        pr_url = f"https://github.com/{owner_repo}/pull/{pr_num}"
        pr_body = pr_obj.get("body", "") or ""
        pr_user = (pr_obj.get("user") or {}).get("login", "")
        labels_list = [l.get("name", "").lower() for l in pr_obj.get("labels", []) if isinstance(l, dict)]
        head_ref = ((pr_obj.get("head") or {}).get("ref", "") or "").lower()

        # Labels (Exact Match)
        for lbl in labels_list:
            if lbl in PR_INTERACTIVE_AI_LABELS:
                clue = f"PR #{pr_num} Label: '{lbl}'"
                pr_clues.append(clue)
                interactive_clues.append(clue)
            if lbl in PR_AUTONOMOUS_AI_LABELS:
                clue = f"PR #{pr_num} Label: '{lbl}' (Autonomous Agent)"
                pr_clues.append(clue)
                autonomous_clues.append(clue)
            if lbl in PR_DEVOPS_BOT_LABELS:
                clue = f"PR #{pr_num} Label: '{lbl}'"
                pr_clues.append(clue)
                devops_clues.append(clue)

        # PR Checkboxes
        for pat, desc in PR_BODY_CHECKBOX_PATTERNS:
            if re.search(pat, pr_body, re.IGNORECASE):
                clue = f"PR #{pr_num} Checkbox: {desc}"
                pr_clues.append(clue)
                interactive_clues.append(clue)

        # PR Body Attribution
        for pat, desc in PR_BODY_ATTRIBUTION_PATTERNS:
            if re.search(pat, pr_body, re.IGNORECASE):
                clue = f"PR #{pr_num} Body: {desc}"
                pr_clues.append(clue)
                if "Sweep" in desc or "Devin" in desc:
                    autonomous_clues.append(clue)
                else:
                    interactive_clues.append(clue)

        # PR Author
        if re.search(r"^sweep(?:-ai)?(?:\[bot\])?$", pr_user, re.IGNORECASE):
            clue = f"PR #{pr_num} Author: Sweep AI"
            pr_clues.append(clue)
            autonomous_clues.append(clue)
        elif re.search(r"^devin(?:-ai)?(?:-integration)?(?:\[bot\])?$", pr_user, re.IGNORECASE):
            clue = f"PR #{pr_num} Author: Devin AI"
            pr_clues.append(clue)
            autonomous_clues.append(clue)
        elif re.search(r"^(?:dependabot|renovate)(?:\[bot\])?$", pr_user, re.IGNORECASE):
            clue = f"PR #{pr_num} Author: {pr_user}"
            pr_clues.append(clue)
            devops_clues.append(clue)

        # PR Branch
        if head_ref.startswith("sweep/") or head_ref.startswith("sweep-"):
            clue = f"PR #{pr_num} Branch: sweep/*"
            pr_clues.append(clue)
            autonomous_clues.append(clue)
        elif head_ref.startswith("devin/") or head_ref.startswith("devin-"):
            clue = f"PR #{pr_num} Branch: devin/*"
            pr_clues.append(clue)
            autonomous_clues.append(clue)
        elif head_ref.startswith("dependabot/") or head_ref.startswith("renovate/"):
            clue = f"PR #{pr_num} Branch: {head_ref.split('/')[0]}/*"
            pr_clues.append(clue)
            devops_clues.append(clue)

    # Category determination
    if interactive_clues:
        return "INTERACTIVE_AI_COAUTHORED", interactive_clues, pr_clues
    elif autonomous_clues:
        return "AUTONOMOUS_AI_AGENT", autonomous_clues, pr_clues
    elif devops_clues:
        return "DETERMINISTIC_DEVOPS_BOT", devops_clues, pr_clues
    else:
        return "PURE_HUMAN", [], pr_clues

def main():
    repos = get_target_repos()
    max_repos = 50
    commits_per_repo = 100

    all_dataset_rows = []

    print("=" * 80)
    print(f"BUILDING COMPLETE DATASET: 5,000 COMMITS ACROSS {max_repos} REPOSITORIES")
    print("=" * 80)

    start_time = time.time()

    for idx, (repo_alias, owner_repo, repo_url) in enumerate(repos[:max_repos], 1):
        print(f"[{idx:2d}/{max_repos}] Fetching {owner_repo}...")

        commits_url = f"https://api.github.com/repos/{owner_repo}/commits?per_page={commits_per_repo}"
        commits, err = fetch_json(commits_url)
        if err or not commits:
            print(f"   Warning: failed to fetch commits for {owner_repo} ({err})")
            continue

        prs_url = f"https://api.github.com/repos/{owner_repo}/pulls?state=all&per_page=100"
        prs, pr_err = fetch_json(prs_url)
        pr_by_num = {}
        pr_by_sha = {}
        if prs and isinstance(prs, list):
            for pr in prs:
                num = pr.get("number")
                if num: pr_by_num[str(num)] = pr
                head_sha = (pr.get("head") or {}).get("sha")
                merge_sha = pr.get("merge_commit_sha")
                if head_sha: pr_by_sha[head_sha] = pr
                if merge_sha: pr_by_sha[merge_sha] = pr

        for c in commits:
            sha = c.get("sha", "")
            short_sha = sha[:7]
            commit_link = f"https://github.com/{owner_repo}/commit/{sha}"
            raw_msg = (c.get("commit", {}).get("message", "") or "").strip()
            first_line = raw_msg.split("\n")[0] if raw_msg else ""
            git_author = c.get("commit", {}).get("author", {}) or {}
            gh_author = c.get("author") or {}
            gh_committer = c.get("committer") or {}

            # Match PR
            matched_pr = None
            if sha in pr_by_sha:
                matched_pr = pr_by_sha[sha]
            else:
                m = re.search(r"#(\d+)", raw_msg)
                if m and m.group(1) in pr_by_num:
                    matched_pr = pr_by_num[m.group(1)]

            # 1. Baseline Git-only classification
            base_cat, base_clues, _ = classify_commit(c, pr_obj=None, owner_repo=owner_repo)

            # 2. Multi-Modal classification
            multi_cat, multi_clues, pr_clues = classify_commit(c, pr_obj=matched_pr, owner_repo=owner_repo)

            pr_number = matched_pr.get("number") if matched_pr else None
            pr_link = f"https://github.com/{owner_repo}/pull/{pr_number}" if pr_number else None
            pr_title = matched_pr.get("title", "") if matched_pr else ""
            pr_user = (matched_pr.get("user") or {}).get("login", "") if matched_pr else ""
            pr_labels_str = "; ".join([l.get("name", "") for l in matched_pr.get("labels", [])]) if matched_pr else ""
            pr_head_ref = (matched_pr.get("head") or {}).get("ref", "") if matched_pr else ""
            pr_body_snip = (matched_pr.get("body", "") or "")[:200].replace("\n", " ").strip() if matched_pr else ""

            is_ai = 1 if multi_cat in ("INTERACTIVE_AI_COAUTHORED", "AUTONOMOUS_AI_AGENT") else 0
            is_autonomous = 1 if multi_cat == "AUTONOMOUS_AI_AGENT" else 0
            is_devops = 1 if multi_cat == "DETERMINISTIC_DEVOPS_BOT" else 0
            is_human = 1 if multi_cat == "PURE_HUMAN" else 0
            uncovered_pr = 1 if (base_cat == "PURE_HUMAN" and is_ai == 1) else 0

            row = {
                "repo_alias": repo_alias,
                "repo_name": owner_repo,
                "repo_url": repo_url,
                "commit_sha": sha,
                "commit_short_sha": short_sha,
                "commit_url": commit_link,
                "commit_date": git_author.get("date", ""),
                "author_name": git_author.get("name", ""),
                "author_email": git_author.get("email", ""),
                "author_login": gh_author.get("login", ""),
                "committer_login": gh_committer.get("login", ""),
                "commit_title": first_line,
                "commit_message": raw_msg,
                "has_pr": True if matched_pr else False,
                "pr_number": pr_number or "",
                "pr_url": pr_link or "",
                "pr_title": pr_title,
                "pr_author_login": pr_user,
                "pr_labels": pr_labels_str,
                "pr_head_ref": pr_head_ref,
                "pr_body_excerpt": pr_body_snip,
                "baseline_category": base_cat,
                "multimodal_category": multi_cat,
                "is_ai_assisted": is_ai,
                "is_autonomous_agent": is_autonomous,
                "is_devops_bot": is_devops,
                "is_pure_human": is_human,
                "uncovered_by_pr": uncovered_pr,
                "detection_clues": "; ".join(multi_clues) if multi_clues else "None",
                "pr_clues": "; ".join(pr_clues) if pr_clues else "None"
            }
            all_dataset_rows.append(row)

        time.sleep(0.05)

    elapsed = time.time() - start_time
    total_count = len(all_dataset_rows)

    print("\n" + "=" * 80)
    print(f"DATASET GENERATION FINISHED in {elapsed:.1f}s")
    print(f"Total Rows Collected: {total_count:,}")
    print("=" * 80)

    # Summary counts
    cat_counts = {}
    for r in all_dataset_rows:
        cat = r["multimodal_category"]
        cat_counts[cat] = cat_counts.get(cat, 0) + 1

    for cat, cnt in sorted(cat_counts.items()):
        print(f"  - {cat:30}: {cnt:5} ({cnt/total_count*100:5.2f}%)")

    # Determine output directory
    output_dir = Path(__file__).resolve().parent.parent / "data"
    if not output_dir.exists():
        output_dir = Path(".")

    # 1. Export CSV
    csv_file = output_dir / "dataset_5000_commits.csv"
    if all_dataset_rows:
        fields = list(all_dataset_rows[0].keys())
        with open(csv_file, "w", encoding="utf-8-sig", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=fields)
            writer.writeheader()
            writer.writerows(all_dataset_rows)
        print(f"Saved CSV dataset to '{csv_file}' ({os.path.getsize(csv_file):,} bytes)")

    # 2. Export JSON
    json_file = output_dir / "dataset_5000_commits.json"
    with open(json_file, "w", encoding="utf-8") as f:
        json.dump({
            "metadata": {
                "total_commits": total_count,
                "total_repositories": max_repos,
                "exported_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                "category_counts": cat_counts
            },
            "commits": all_dataset_rows
        }, f, indent=2)
    print(f"Saved JSON dataset to '{json_file}' ({os.path.getsize(json_file):,} bytes)")

if __name__ == "__main__":
    main()
